import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { PACKAGES, docsDir, escapeProse, repoUrl, scriptsDir, shortName, vPre } from './family.mjs'

const snapshotPath = join(scriptsDir, 'api-snapshot.json')
if (!existsSync(snapshotPath)) {
    console.error('generate-api: docs/scripts/api-snapshot.json is missing — run docs/scripts/reflect.sh (or `make docs-api`) first.')
    process.exit(1)
}

const snapshot = JSON.parse(readFileSync(snapshotPath, 'utf8'))
const apiEntries = snapshot.filter((entry) => entry.isApi)
const bySlug = Object.fromEntries(PACKAGES.map((pkg) => [pkg.slug, pkg]))
const pageOf = new Map(apiEntries.map((entry) => [entry.class, `/api/classes/${shortName(entry.class)}`]))

function shortenType(type) {
    if (type === undefined || type === null) {
        return 'mixed'
    }

    return type.replaceAll(/\\?Rasuvaeff\\Yii3AbTesting\w*\\/g, '')
}

function formatParam(p) {
    const variadic = p.variadic ? '...' : ''
    const def = p.default !== null ? ` = ${shortenType(p.default)}` : ''

    return `${shortenType(p.type)} ${variadic}$${p.name}${def}`
}

// Short signatures on one line; anything longer one parameter per line with a
// trailing comma — the way this codebase writes them.
function signature(name, params, returnType, isStatic) {
    const prefix = isStatic ? 'static ' : ''
    const returns = returnType === undefined ? '' : `: ${shortenType(returnType)}`
    const oneLine = `${prefix}${name}(${params.map(formatParam).join(', ')})${returns}`
    if (params.length <= 2 && oneLine.length <= 88) {
        return oneLine
    }

    return `${prefix}${name}(\n${params.map((p) => `    ${formatParam(p)},`).join('\n')}\n)${returns}`
}

function firstSentence(text, maxLen) {
    const flat = text.replace(/\s+/g, ' ').replaceAll('`', '').trim()
    if (flat === '') return ''
    const boundary = flat.slice(0, maxLen + 1).search(/[.!?](\s|$)/)
    if (boundary !== -1 && boundary <= maxLen) return flat.slice(0, boundary + 1)
    if (flat.length <= maxLen) return flat
    const truncated = flat.slice(0, maxLen - 1)

    return truncated.slice(0, truncated.lastIndexOf(' ')).trimEnd() + '…'
}

function typeLink(className) {
    const page = pageOf.get(className)

    return page === undefined ? `\`${shortenType(className)}\`` : `[\`${shortName(className)}\`](${page})`
}

function paramList(params) {
    const documented = params.filter((p) => p.description !== '')

    return documented.map((p) => `- \`$${p.name}\` — ${escapeProse(p.description)}`).join('\n')
}

function renderClass(entry) {
    const pkg = bySlug[entry.package]
    const name = shortName(entry.class)
    const kind = { class: 'Class', interface: 'Interface', enum: 'Enum' }[entry.kind]
    const source = `${repoUrl(pkg)}/blob/master/src/${entry.class.slice(pkg.namespace.length + 1).replaceAll('\\', '/')}.php`
    const description = firstSentence(entry.summary, 155) || `${name} — ${entry.kind} in ${pkg.name}.`

    const out = []
    out.push('---')
    out.push(`title: ${JSON.stringify(name)}`)
    out.push(`description: ${JSON.stringify(description)}`)
    out.push('editLink: false')
    out.push('---')
    out.push('')
    out.push('<!-- AUTO-GENERATED by docs/scripts/generate-api.mjs from docs/scripts/api-snapshot.json — edit the docblock in src/, not this file. -->')
    out.push('')
    out.push(`# ${name}`)
    out.push('')
    out.push(`\`${entry.class}\``)
    out.push('')

    const meta = [`**${kind}**`, `[${pkg.name}](/packages/${pkg.slug})`, `[Source](${source})`]
    if (entry.extends) meta.push(`extends ${typeLink(entry.extends)}`)
    const family = entry.implements.filter((i) => i.startsWith('Rasuvaeff\\'))
    if (family.length > 0) meta.push(`${entry.kind === 'interface' ? 'extends' : 'implements'} ${family.map(typeLink).join(', ')}`)
    out.push(meta.join(' · '))
    out.push('')

    const body = []
    if (entry.summary) {
        body.push(escapeProse(entry.summary))
        body.push('')
    }

    if (entry.cases.length > 0) {
        body.push('## Cases')
        body.push('')
        body.push('| Case | Value | Meaning |')
        body.push('|---|---|---|')
        for (const c of entry.cases) {
            body.push(`| \`${c.name}\` | ${c.value === null ? '—' : `\`${JSON.stringify(c.value)}\``} | ${escapeProse(c.summary.replace(/\s+/g, ' '))} |`)
        }
        body.push('')
    }

    if (entry.constants.length > 0) {
        body.push('## Constants')
        body.push('')
        for (const c of entry.constants) {
            body.push(`### ${c.name}`)
            body.push('')
            body.push('```php')
            body.push(`${c.name} = ${c.value}`)
            body.push('```')
            body.push('')
            if (c.summary) {
                body.push(escapeProse(c.summary))
                body.push('')
            }
        }
    }

    if (entry.constructor !== null && entry.kind === 'class') {
        body.push('## Constructor')
        body.push('')
        body.push('```php')
        body.push(signature(`new ${name}`, entry.constructor, undefined, false))
        body.push('```')
        body.push('')
        const params = paramList(entry.constructor)
        if (params) {
            body.push(params)
            body.push('')
        }
    }

    if (entry.publicProperties.length > 0) {
        body.push('## Properties')
        body.push('')
        body.push('| Property | Type | Readonly | Description |')
        body.push('|---|---|---|---|')
        for (const p of entry.publicProperties) {
            body.push(`| \`${p.name}\` | \`${shortenType(p.type)}\` | ${p.readonly ? 'yes' : 'no'} | ${escapeProse(p.summary.replace(/\s+/g, ' '))} |`)
        }
        body.push('')
    }

    if (entry.publicMethods.length > 0) {
        body.push('## Methods')
        body.push('')
        for (const method of entry.publicMethods) {
            body.push(`### ${method.name}()`)
            body.push('')
            body.push('```php')
            body.push(signature(method.name, method.params, method.returnType ?? 'mixed', method.static))
            body.push('```')
            body.push('')
            if (method.summary) {
                body.push(escapeProse(method.summary))
                body.push('')
            }
            const params = paramList(method.params)
            if (params) {
                body.push(params)
                body.push('')
            }
        }
    }

    out.push(vPre(body.join('\n') || 'No public members beyond the type itself.'))

    return out.join('\n')
}

function renderIndex() {
    const out = []
    out.push('---')
    out.push('title: API reference')
    out.push('description: Every public (@api) class, interface and enum of the five A/B testing packages, reflected from their src/ trees.')
    out.push('editLink: false')
    out.push('---')
    out.push('')
    out.push('<!-- AUTO-GENERATED by docs/scripts/generate-api.mjs — do not edit this file directly. -->')
    out.push('')
    out.push('# API reference')
    out.push('')
    out.push('Every type marked `@api` in the five packages, reflected from `src/` on each build. Types marked `@internal` are not part of the contract and are not listed.')
    out.push('')
    for (const pkg of PACKAGES) {
        const entries = apiEntries.filter((entry) => entry.package === pkg.slug)
        out.push(`## ${pkg.title} {#${pkg.slug}}`)
        out.push('')
        out.push(`[${pkg.name}](/packages/${pkg.slug}) — \`${pkg.namespace}\``)
        out.push('')
        out.push('| Type | Kind | Summary |')
        out.push('|---|---|---|')
        for (const entry of entries) {
            const summary = escapeProse(firstSentence(entry.summary, 120)).replaceAll('|', '\\|')
            out.push(`| [\`${shortName(entry.class)}\`](${pageOf.get(entry.class)}) | ${entry.kind} | ${summary} |`)
        }
        out.push('')
    }

    return out.join('\n')
}

const outDir = join(docsDir, 'api', 'classes')
rmSync(join(docsDir, 'api'), { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

for (const entry of apiEntries) {
    writeFileSync(join(outDir, `${shortName(entry.class)}.md`), renderClass(entry) + '\n', 'utf8')
}
writeFileSync(join(docsDir, 'api', 'index.md'), renderIndex() + '\n', 'utf8')

console.log(`Generated ${apiEntries.length} API pages and the index into api/.`)
