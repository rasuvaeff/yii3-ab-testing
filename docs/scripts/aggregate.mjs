import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { PACKAGES, docsDir, packageDir, repoUrl, vPre } from './family.mjs'

// Every package's README.md and llms.txt become site pages, unedited apart
// from the header and link targets: the package repository stays the single
// source of truth, and nothing here can drift from what Packagist shows.

const failures = []

// Links a README makes relative to its own repository. A few point at pages
// this site renders itself; everything else goes to the file on GitHub.
function rewriteLinks(markdown, pkg) {
    const siteTargets = {
        'llms.txt': `/llms/${pkg.slug}`,
        'docs/integration.md': '/integration',
    }

    return markdown.replace(/\]\((?!https?:|#|\/|mailto:)([^)\s]+)\)/g, (_match, target) => {
        const [path, fragment] = target.split('#')
        if (siteTargets[path] !== undefined) {
            return `](${siteTargets[path]}${fragment ? '#' + fragment : ''})`
        }

        return `](${repoUrl(pkg)}/blob/master/${path.replace(/^\.\//, '')}${fragment ? '#' + fragment : ''})`
    })
}

// The H1, the badge row and the "Русская версия" switch belong to the GitHub
// view of the README; the page supplies its own title and the site is EN-only.
function stripHeader(markdown) {
    const lines = markdown.split('\n')
    const kept = []
    let inHeader = true
    for (const line of lines) {
        if (inHeader && (line.startsWith('# ') || line.startsWith('[![') || /^\[Русская версия\]/.test(line) || line.trim() === '')) {
            continue
        }
        inHeader = false
        kept.push(line)
    }

    return kept.join('\n')
}

function frontmatter(title, description) {
    return `---\ntitle: ${JSON.stringify(title)}\ndescription: ${JSON.stringify(description)}\neditLink: false\n---\n\n`
}

function banner(source, pkg) {
    return `<!-- AUTO-GENERATED by docs/scripts/aggregate.mjs from ${pkg.dir}/${source} — edit the package repository, not this file. -->\n\n`
}

for (const dir of ['packages', 'llms']) {
    rmSync(join(docsDir, dir), { recursive: true, force: true })
    mkdirSync(join(docsDir, dir), { recursive: true })
}

for (const pkg of PACKAGES) {
    const dir = packageDir(pkg)
    if (dir === null) {
        failures.push(`${pkg.dir}: not found under docs/siblings/ or as a monorepo sibling`)
        continue
    }

    const readme = readFileSync(join(dir, 'README.md'), 'utf8')
    const header =
        `# ${pkg.name}\n\n` +
        `${pkg.summary}\n\n` +
        `| | |\n|---|---|\n` +
        `| Install | \`composer require ${pkg.name}\` |\n` +
        `| Namespace | \`${pkg.namespace}\` |\n` +
        `| Repository | [github.com/rasuvaeff/${pkg.dir}](${repoUrl(pkg)}) |\n` +
        `| API reference | [${pkg.title} classes](/api/#${pkg.slug}) |\n\n`
    writeFileSync(
        join(docsDir, 'packages', `${pkg.slug}.md`),
        frontmatter(pkg.name, `${pkg.name} — ${pkg.summary}`) +
            banner('README.md', pkg) +
            header +
            vPre(rewriteLinks(stripHeader(readme), pkg)),
        'utf8',
    )

    const llms = readFileSync(join(dir, 'llms.txt'), 'utf8')
    writeFileSync(
        join(docsDir, 'llms', `${pkg.slug}.md`),
        frontmatter(`${pkg.name} — llms.txt`, `Compact LLM-oriented API reference for ${pkg.name}: paste it into an AI coding assistant as context.`) +
            banner('llms.txt', pkg) +
            `# llms.txt — ${pkg.name}\n\n` +
            `The compact reference the package ships for AI coding assistants. Raw file: [llms.txt](${repoUrl(pkg)}/blob/master/llms.txt).\n\n` +
            '````markdown\n' +
            llms.trimEnd() +
            '\n````\n',
        'utf8',
    )
}

if (failures.length > 0) {
    console.error(`aggregate: cannot build the family site:\n  - ${failures.join('\n  - ')}`)
    process.exit(1)
}

console.log(`Aggregated README.md and llms.txt of ${PACKAGES.length} packages into packages/ and llms/.`)
